// Turns Patashnik's strategy dictionary into a Dart lookup table.
//
//   dart run tool/bookgen.dart
//
// Reads `third_party/patashnik/qubic.dictionary` and writes
// `lib/src/strategy_book.g.dart`. The dictionary itself is never written to —
// its terms require its moves to be unchanged, and `tool/check.sh` verifies its
// hash on every run.
//
// Every entry is stored in **canonical form**: the board reduced to the
// smallest of its 192 symmetric images, and the move rewritten into that same
// orientation. That is what makes 2929 entries answer for the far larger number
// of positions a game actually reaches, and it is what the dictionary's own
// header instructs (`you will need: (1) a canonical-form routine`).
import 'dart:convert';
import 'dart:io';

import 'package:quadrim_engine/quadrim_engine.dart';

/// Vendored copy, byte for byte. See `third_party/patashnik/NOTICE.md`.
const String _expectedSha256 =
    '38d9b7820fd97269968e6eea32c6448712d0551e66c1f2ed1ce47f74f3069499';

/// The header ends with a rule; everything after it is data.
const String _headerRule = '-----';

void main() {
  final root = Directory.current.path;
  final source = File('$root/../../third_party/patashnik/qubic.dictionary');
  if (!source.existsSync()) {
    stderr.writeln('not found: ${source.path} (run from packages/quadrim_engine)');
    exitCode = 1;
    return;
  }

  final bytes = source.readAsBytesSync();
  final actual = sha256Hex(bytes);
  if (actual != _expectedSha256) {
    stderr.writeln('the dictionary has changed:\n'
        '  expected $_expectedSha256\n'
        '  actual   $actual\n'
        'Its terms require its moves to be unchanged. Restore it, or if this is '
        'a deliberate refresh, update NOTICE.md and _expectedSha256 together.');
    exitCode = 1;
    return;
  }

  final entries = _parse(utf8.decode(bytes));
  stdout.writeln('parsed ${entries.length} entries');

  final book = <String, int>{};
  for (final entry in entries) {
    final form = canonicalise(entry.state);
    final canonicalMove = form.permutation[entry.move];
    final existing = book[form.key];
    if (existing != null && existing != canonicalMove) {
      // Two dictionary lines that are the same position up to symmetry must
      // agree, or the canonical key is not a sound way to store them.
      stderr.writeln('conflict at ${form.key}: $existing vs $canonicalMove');
      exitCode = 1;
      return;
    }
    book[form.key] = canonicalMove;
  }
  stdout.writeln('${book.length} distinct canonical positions');

  final keys = book.keys.toList()..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/bookgen.dart. Do not edit.')
    ..writeln('//')
    ..writeln('// Derived from Oren Patashnik\'s Qubic strategy dictionary:')
    ..writeln('// 2929 strategic moves constructed 1976-77, published as')
    ..writeln('// "Qubic: 4x4x4 Tic-Tac-Toe", Mathematics Magazine 53 (4),')
    ..writeln('// September 1980, pages 202-216; put in its present form by')
    ..writeln('// Ken Thompson in 1978. Used with credit, moves unchanged, as')
    ..writeln('// its terms require. See third_party/patashnik/NOTICE.md.')
    ..writeln('//')
    ..writeln('// Source SHA-256: $_expectedSha256')
    ..writeln('library;')
    ..writeln()
    ..writeln('/// Canonical boards, ${keys.first.length} characters each, '
        'concatenated.')
    ..writeln('///')
    ..writeln('/// `0` empty, `1` the side to move, `2` the other side — the '
        'encoding')
    ..writeln('/// [canonicalKey] produces. Adjacent literals are joined at '
        'compile time,')
    ..writeln('/// so this costs one string rather than ${keys.length}.')
    ..writeln('const String bookBoards =');
  for (var i = 0; i < keys.length; i++) {
    out.writeln("    '${keys[i]}'${i == keys.length - 1 ? ';' : ''}");
  }
  out
    ..writeln()
    ..writeln('/// The strategic move for each board above, in the same order '
        'and in the')
    ..writeln('/// same canonical orientation.')
    ..writeln('const List<int> bookMoves = [');
  for (var i = 0; i < keys.length; i += 20) {
    final row = keys.skip(i).take(20).map((k) => book[k]).join(', ');
    out.writeln('  $row,');
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('/// Cells per board, so the reader need not assume 64.')
    ..writeln('const int bookBoardLength = ${keys.first.length};');

  File('$root/lib/src/strategy_book.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote lib/src/strategy_book.g.dart');
}

final class _Entry {
  _Entry(this.state, this.move);
  final GameState state;
  final int move;
}

List<_Entry> _parse(String text) {
  final lines = text.split('\n');
  final start = lines.indexWhere((l) => l.startsWith(_headerRule));
  if (start < 0) throw StateError('no header rule in the dictionary');

  final entries = <_Entry>[];
  for (final line in lines.skip(start + 1)) {
    if (line.trim().isEmpty) continue;
    final space = line.indexOf(' ');
    if (space < 0) throw StateError('no move on line: $line');
    final board = _decode(line.substring(0, space));
    final move = int.parse(line.substring(space + 1).trim());
    entries.add(_Entry(_replay(board), move));
  }
  return entries;
}

/// Pieces in cell order, digits are runs of empty cells, cells past the end of
/// the string are empty. `xo1x8x8o41o` is the example the dictionary documents.
List<String> _decode(String position) {
  final board = List<String>.filled(64, '.');
  var at = 0;
  for (final match in RegExp(r'\d+|[xo]').allMatches(position)) {
    final token = match.group(0)!;
    if (token == 'x' || token == 'o') {
      board[at++] = token;
    } else {
      at += int.parse(token);
    }
  }
  if (at > 64) throw StateError('position describes $at cells: $position');
  return board;
}

/// A [GameState] holding [board], with the first player to move.
///
/// The dictionary gives a position, not a move order, so one is invented by
/// alternating. Any order reaches the same board, and none of them ends early:
/// a completed line in an intermediate position would have to be present in the
/// final one too, and a dictionary position is one where play continues.
GameState _replay(List<String> board) {
  final xs = [for (var i = 0; i < 64; i++) if (board[i] == 'x') i];
  final os = [for (var i = 0; i < 64; i++) if (board[i] == 'o') i];
  if (xs.length != os.length) {
    throw StateError('${xs.length} x against ${os.length} o');
  }
  final moves = <int>[];
  for (var i = 0; i < xs.length; i++) {
    moves..add(xs[i])..add(os[i]);
  }
  return GameState.fromMoves(moves);
}

/// SHA-256 without a package dependency: this tool has none and is not worth
/// giving one.
String sha256Hex(List<int> message) {
  const k = [
    0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1,
    0x923f82a4, 0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3,
    0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786,
    0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
    0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147,
    0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13,
    0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b,
    0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
    0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a,
    0x5b9cca4f, 0x682e6ff3, 0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208,
    0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
  ];
  var h = [
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
    0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ];
  const mask = 0xffffffff;
  int rotr(int x, int n) => ((x >> n) | (x << (32 - n))) & mask;

  final padded = [...message, 0x80];
  while (padded.length % 64 != 56) {
    padded.add(0);
  }
  final bits = message.length * 8;
  for (var i = 7; i >= 0; i--) {
    padded.add((bits >> (i * 8)) & 0xff);
  }

  final w = List<int>.filled(64, 0);
  for (var chunk = 0; chunk < padded.length; chunk += 64) {
    for (var i = 0; i < 16; i++) {
      final j = chunk + i * 4;
      w[i] = (padded[j] << 24) |
          (padded[j + 1] << 16) |
          (padded[j + 2] << 8) |
          padded[j + 3];
    }
    for (var i = 16; i < 64; i++) {
      final s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >> 3);
      final s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) & mask;
    }
    var [a, b, c, d, e, f, g, hh] = h;
    for (var i = 0; i < 64; i++) {
      final s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      final ch = (e & f) ^ (~e & g);
      final t1 = (hh + s1 + ch + k[i] + w[i]) & mask;
      final s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      final maj = (a & b) ^ (a & c) ^ (b & c);
      final t2 = (s0 + maj) & mask;
      hh = g;
      g = f;
      f = e;
      e = (d + t1) & mask;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) & mask;
    }
    final next = [a, b, c, d, e, f, g, hh];
    for (var i = 0; i < 8; i++) {
      h[i] = (h[i] + next[i]) & mask;
    }
  }
  return h.map((v) => v.toRadixString(16).padLeft(8, '0')).join();
}
